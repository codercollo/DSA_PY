# 2. Use Big O Notation to describe the time complexity of an algorithm that
# takes 2N2

# Ans: Big O Notations ignore constants that aren't an exponent:
# so for 2N2 we can drop the regular numbers from the expression  
# to  O(N2) quadratic time .

# Big O Notation ignores constant coefficients but keeps 
# exponents. In this case, 2N^2 we drop the constant coefficient 2
# but retain N^2 - quadratic time. 